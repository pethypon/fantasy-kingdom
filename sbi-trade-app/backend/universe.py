def tickers() -> list[str]:
    return [t[0] for t in UNIVERSE]


def display_name(ticker: str) -> str:
    for t, name, _ in UNIVERSE:
        if t == ticker:
            return name
    return ticker


def news_keyword(ticker: str) -> str:
    for t, _, kw in UNIVERSE:
        if t == ticker:
            return kw
    return ticker
